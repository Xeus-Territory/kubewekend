#!/usr/bin/env bash
# shellcheck shell=bash
# =============================================================================
# Kubewekend CLI library: completion command
# =============================================================================
# `completion bash|zsh` prints a shell completion script. Nothing in it is hand-maintained:
#   commands      from the COMMANDS section of show_help
#   subcommands   from each command's own SUBCOMMANDS help section
#   utility tags  from UTILITY_REGISTRY      version names and groups  from VERSION_REGISTRY
#   ansible flags from parse_ansible_opts    inventory hosts           read from the inventory when you press TAB
# Add a command, a utility or a flag and the next `completion` run includes it; scripts/checks/check_setup.py
# fails on commit when the generated script misses any of them.
# Sourced by scripts/setup.sh (never run it directly).

# ---------------------------------------------------------------------------
# COMMAND: completion
# ---------------------------------------------------------------------------
cmd_completion_help() {
    cat <<'EOF'
kubewekend completion - Shell completion for setup.sh

SUBCOMMANDS
  bash          Print the bash completion script
  zsh           Print the zsh completion script (zsh loads it through bashcompinit)

Completes commands, subcommands, utility tags (kind|k3s|rke2 utils <TAB>), version names, ansible flags and the hosts
of your inventory. The script is generated from the CLI itself, so it is never out of date.

EXAMPLES
  # bash: add to ~/.bashrc
  source <(./scripts/setup.sh completion bash)

  # zsh: add to ~/.zshrc
  source <(./scripts/setup.sh completion zsh)

  # or write it once and source the file
  ./scripts/setup.sh completion bash > ~/.kubewekend-completion.bash
EOF
}

cmd_completion() {
    local sub="${1:-help}"
    case "$sub" in
        bash|zsh) completion_generate "$sub" ;;
        *)        cmd_completion_help ;;
    esac
}

# Remove colour escape codes from stdin (the help screens colour their headings on a terminal)
_completion_plain() { sed $'s/\033\\[[0-9;]*m//g'; }

# Top-level command names, from the COMMANDS section of show_help
_completion_commands() {
    show_help | _completion_plain | awk '/^COMMANDS/ { f = 1; next } /^[A-Z]/ { f = 0 } f && /^  [a-z]/ { print $1 }'
}

# Subcommand names of one command, from its SUBCOMMANDS help section (nothing when it has none)
_completion_subcommands() {
    declare -F "cmd_${1}_help" >/dev/null || return 0
    "cmd_${1}_help" | _completion_plain | awk '/^SUBCOMMANDS/ { f = 1; next } /^[A-Z]/ { f = 0 } f && /^  [a-z]/ { print $1 }' | sort -u
}

# Space-joined words of stdin
_completion_words() { paste -sd' ' -; }

completion_generate() {
    local shell="$1"
    printf '# kubewekend %s completion, generated by `./scripts/setup.sh completion %s`. Do not edit: regenerate it.\n' "$shell" "$shell"
    if [[ "$shell" == "zsh" ]]; then
        cat <<'ZSH'
# zsh runs bash-style completion functions through bashcompinit
if ! (( $+functions[compdef] )); then autoload -U +X compinit && compinit -i; fi
autoload -U +X bashcompinit && bashcompinit
ZSH
    fi
    _completion_hosts_function
    _completion_main_function
    printf 'complete -F _kubewekend_complete setup.sh ./scripts/setup.sh %s\n' "$PROJECT_ROOT/scripts/setup.sh"
}

# Host names of the inventory, read when TAB is pressed
_completion_hosts_function() {
    printf '_kubewekend_hosts() {\n    local f="%s"\n' "$HOSTS_FILE"
    cat <<'HOSTS'
    [[ -f "$f" ]] && awk '/^\[/ { next } NF && $1 !~ /^#/ && /ansible_host=/ { print $1 }' "$f"
}
HOSTS
}

_completion_main_function() {
    local commands
    commands=$(_completion_commands | _completion_words)
    cat <<'HEAD'
_kubewekend_complete() {
    local cur prev cmd sub words off=1 pos
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    if [[ "${COMP_WORDS[1]:-}" == "--debug" ]]; then off=2; fi
    pos=$((COMP_CWORD - off + 1))
    cmd="${COMP_WORDS[off]:-}"
    sub="${COMP_WORDS[off+1]:-}"
    words=""
HEAD
    printf '    if (( pos == 1 )); then\n        words="%s --debug"\n' "$commands"
    cat <<'MID'
    elif [[ "$prev" == "--host" || "$prev" == "-H" ]]; then
        words="$(_kubewekend_hosts)"
    else
        case "$cmd" in
MID
    _completion_arms
    cat <<'TAIL'
        esac
    fi
    COMPREPLY=( $(compgen -W "$words" -- "$cur") )
}
TAIL
}

# One `case` arm per command, with the words that can follow it
_completion_arms() {
    local c subs flags tags names groups entry name group
    flags=$(declare -f parse_ansible_opts | grep -oE -- '--[a-z][a-z-]*|-H' | sort -u | _completion_words)
    tags=$(for entry in "${UTILITY_REGISTRY[@]}"; do _util_field "$entry" 0; echo; done | grep . | _completion_words)
    names=$(for entry in "${VERSION_REGISTRY[@]}"; do IFS='|' read -r name _ <<< "$entry"; echo "$name"; done | _completion_words)
    groups=$(for entry in "${VERSION_REGISTRY[@]}"; do IFS='|' read -r _ group _ <<< "$entry"; echo "$group"; done | sort -u | _completion_words)
    for c in $(_completion_commands); do
        subs=$(_completion_subcommands "$c" | _completion_words)
        case "$c" in
            help|status) continue ;;
            kind|k3s|rke2)
                printf '        %s)\n            if (( pos == 2 )); then words="%s"\n' "$c" "$subs"
                printf '            elif [[ "$sub" == "utils" ]]; then words="%s --list %s"\n' "$tags" "$flags"
                printf '            else words="%s"; fi ;;\n' "$flags" ;;
            vagrant)
                printf '        vagrant)\n            if (( pos == 2 )); then words="%s"\n' "$subs"
                printf '            else words="k8s-master-machine k8s-worker-machine-1 k8s-worker-machine-2 k8s-worker-machine-3 $(_kubewekend_hosts)"; fi ;;\n' ;;
            inventory)
                printf '        inventory)\n            if (( pos == 2 )); then words="%s"\n' "$subs"
                printf '            elif [[ "$sub" == "ping" ]]; then words="all standalone-masters standalone-workers standalone-all ha_master_init ha_master_join ha_master ha_worker ha_all"; fi ;;\n' ;;
            config)
                printf '        config)\n            if (( pos == 2 )); then words="%s --list"\n' "$subs"
                printf '            else case "$sub" in list|--list|-l) words="kind k3s rke2 utils" ;; show|worker-show) words="--raw" ;; validate) words="--strict" ;; esac; fi ;;\n' ;;
            versions)
                printf '        versions)\n            if (( pos == 2 )); then words="%s"\n' "$subs"
                printf '            else case "$sub" in\n                list|ls) words="%s %s" ;;\n' "$groups" "$names"
                printf '                bump) if (( pos == 3 )); then words="%s"; else words="--dry-run --yes"; fi ;;\n' "$names"
                printf '                sync) words="--check" ;;\n            esac; fi ;;\n' ;;
            doctor)
                printf '        doctor) words="--ping" ;;\n' ;;
            *)
                printf '        %s) if (( pos == 2 )); then words="%s"; fi ;;\n' "$c" "$subs" ;;
        esac
    done
}
